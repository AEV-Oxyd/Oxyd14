using Content.Client.UserInterface.StateRouting;
using Content.Shared.CartridgeLoader.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class NotekeeperUiFragment : BoxContainer, IBuiStateReceiver
{
    private readonly BuiStateHandlers _handlers = new();
    public BuiStateReceiveResult ReceiveBuiState(BoundUserInterfaceState s) => _handlers.Receive(s);

    public event Action<string>? OnNoteAdded;
    public event Action<string>? OnNoteRemoved;
    public event Action<string>? OnOpenFile;
    public event Action<string, string>? OnSaveFile;
    public event Action<string, string>? OnCreateFile;
    public event Action<string>? OnDeleteFile;

    private string? _currentLoadedPath;
    private bool _isDirty;
    private bool _isUpdatingUi;
    private List<string> _availableFiles = new();

    public NotekeeperUiFragment()
    {
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;

        _handlers.On<NotekeeperUiState>(UpdateState);

        FileSelector.OnItemSelected += args =>
        {
            if (_isUpdatingUi) return;
            if (args.Id >= 0 && args.Id < _availableFiles.Count)
            {
                var targetPath = _availableFiles[args.Id];
                OnOpenFile?.Invoke(targetPath);
            }
        };

        NewFileButton.OnPressed += _ =>
        {
            NewFileContainer.Visible = !NewFileContainer.Visible;
            if (NewFileContainer.Visible)
            {
                NewFileNameInput.Text = "";
                NewFileNameInput.GrabKeyboardFocus();
            }
        };

        CancelCreateButton.OnPressed += _ =>
        {
            NewFileContainer.Visible = false;
            NewFileNameInput.Text = "";
        };

        ConfirmCreateButton.OnPressed += _ => SubmitCreateFile();
        NewFileNameInput.OnTextEntered += _ => SubmitCreateFile();

        SaveButton.OnPressed += _ =>
        {
            if (string.IsNullOrEmpty(_currentLoadedPath)) return;
            var content = Rope.Collapse(DocumentEditor.TextRope);
            _isDirty = false;
            StatusIndicator.Text = "[Saved]";
            StatusIndicator.FontColorOverride = Color.FromHex("#00FF88");
            OnSaveFile?.Invoke(_currentLoadedPath, content);
        };

        DeleteFileButton.OnPressed += _ =>
        {
            if (string.IsNullOrEmpty(_currentLoadedPath)) return;
            OnDeleteFile?.Invoke(_currentLoadedPath);
        };

        DocumentEditor.OnTextChanged += _ =>
        {
            if (_isUpdatingUi) return;
            _isDirty = true;
            if (StatusIndicator.Text != "[Read Only]")
            {
                StatusIndicator.Text = "[Modified]";
                StatusIndicator.FontColorOverride = Color.FromHex("#FFE066");
            }
        };
    }

    private void SubmitCreateFile()
    {
        var rawName = NewFileNameInput.Text.Trim();
        if (!string.IsNullOrWhiteSpace(rawName))
        {
            OnCreateFile?.Invoke(rawName, "");
            NewFileContainer.Visible = false;
            NewFileNameInput.Text = "";
        }
    }

    public void UpdateState(NotekeeperUiState state)
    {
        _isUpdatingUi = true;
        try
        {
            _availableFiles = new List<string>(state.AvailableFiles);

            FileSelector.Clear();
            var selectedIdx = -1;
            for (var i = 0; i < state.AvailableFiles.Count; i++)
            {
                var path = state.AvailableFiles[i];
                var display = path.StartsWith("/disk/")
                    ? $"[Disk] {GetFileName(path)}"
                    : GetFileName(path);

                FileSelector.AddItem(display, i);
                if (path == state.CurrentFilePath)
                    selectedIdx = i;
            }

            if (selectedIdx >= 0)
                FileSelector.SelectId(selectedIdx);

            PathLabel.Text = state.CurrentFilePath;

            if (state.IsReadOnly)
            {
                StatusIndicator.Text = "[Read Only]";
                StatusIndicator.FontColorOverride = Color.FromHex("#FF8888");
                DocumentEditor.Editable = false;
                SaveButton.Disabled = true;
                DeleteFileButton.Disabled = true;
            }
            else
            {
                DocumentEditor.Editable = true;
                SaveButton.Disabled = false;
                DeleteFileButton.Disabled = state.CurrentFilePath == "/notes/shift_notes.txt";
            }

            if (state.CurrentFilePath != _currentLoadedPath || !_isDirty)
            {
                _currentLoadedPath = state.CurrentFilePath;
                _isDirty = false;
                DocumentEditor.TextRope = new Rope.Leaf(state.FileContent);
                if (!state.IsReadOnly)
                {
                    StatusIndicator.Text = "[Saved]";
                    StatusIndicator.FontColorOverride = Color.FromHex("#00FF88");
                }
            }
        }
        finally
        {
            _isUpdatingUi = false;
        }
    }

    public void UpdateState(List<string> notes)
    {
        var content = string.Join("\n", notes);
        UpdateState(new NotekeeperUiState(notes, _currentLoadedPath ?? "/notes/shift_notes.txt", "shift_notes.txt", content, _availableFiles, false));
    }

    private static string GetFileName(string path)
    {
        var lastSlash = path.LastIndexOf('/');
        return lastSlash >= 0 ? path.Substring(lastSlash + 1) : path;
    }
}
