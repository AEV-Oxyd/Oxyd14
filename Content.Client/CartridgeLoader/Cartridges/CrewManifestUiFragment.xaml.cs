using Content.Client.CrewManifest.UI;
using Content.Client.UserInterface.StateRouting;
using Content.Shared.CartridgeLoader.Cartridges;
using Content.Shared.CrewManifest;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class CrewManifestUiFragment : BoxContainer, IBuiStateReceiver
{
    private readonly BuiStateHandlers _handlers = new();
    public BuiStateReceiveResult ReceiveBuiState(BoundUserInterfaceState s) => _handlers.Receive(s);

    public CrewManifestUiFragment()
    {
        RobustXamlLoader.Load(this);

        StationName.AddStyleClass("LabelBig");
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;

        _handlers.On<CrewManifestUiState>(s => UpdateState(s.StationName, s.Entries));
    }

    public void UpdateState(string stationName, CrewManifestEntries? entries)
    {
        CrewManifestListing.RemoveAllChildren();

        StationNameContainer.Visible = entries != null;
        StationName.Text = stationName;

        if (entries == null)
            return;

        CrewManifestListing.AddCrewManifestEntries(entries);
    }
}
