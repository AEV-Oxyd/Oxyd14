using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.PDA;

[Virtual]
[GenerateTypedNameReferences]
public partial class PdaWindow : BaseWindow
{
    public string? BorderColor
    {
        get => Border.ActualModulateSelf.ToHex();
        set
        {
            var col = Color.FromHex(value, Color.FromHex("#5a5a5a"));
            Border.ModulateSelfOverride = col;
            Background.ModulateSelfOverride = col.WithAlpha(0.35f);
        }
    }

    public string? AccentHColor
    {
        get => AccentH.ActualModulateSelf.ToHex();
        set
        {
            AccentH.ModulateSelfOverride = Color.FromHex(value, Color.White);
            AccentH.Visible = value != null;
        }
    }

    public string? AccentVColor
    {
        get => AccentV.ActualModulateSelf.ToHex();
        set
        {
            AccentV.ModulateSelfOverride = Color.FromHex(value, Color.White);
            AccentV.Visible = value != null;
        }
    }

    public PdaWindow()
    {
        RobustXamlLoader.Load(this);

        CloseButton.OnPressed += _ => Close();
        CloseButtonPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#202023"),
            BorderColor = Color.FromHex("#5a5a5a"),
            BorderThickness = new Thickness(1)
        };
        CloseButton.OnMouseEntered += _ =>
        {
            CloseButtonLabel.FontColorOverride = Color.FromHex("#ff5555");
            CloseButtonPanel.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#3a2023"),
                BorderColor = Color.FromHex("#ff5555"),
                BorderThickness = new Thickness(1)
            };
        };
        CloseButton.OnMouseExited += _ =>
        {
            CloseButtonLabel.FontColorOverride = Color.FromHex("#cfcfd4");
            CloseButtonPanel.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#202023"),
                BorderColor = Color.FromHex("#5a5a5a"),
                BorderThickness = new Thickness(1)
            };
        };
        XamlChildren = ContentsContainer.Children;

        AccentH.Visible = false;
        AccentV.Visible = false;
        Resizable = true;
    }

    private bool _embedded;

    public void StripDetailElements(bool stripped = true)
    {
        _embedded = stripped;
        Resizable = !stripped;
        Background.Visible = !stripped;
        AccentH.Visible = !stripped;
        AccentV.Visible = !stripped;
        Border.Visible = !stripped;
        BezelFooterPanel.Visible = !stripped;
        HeadingBar.Visible = !stripped;
        ContentBorder.Visible = !stripped;
        ScreenInsetControl.Margin = stripped ? new Thickness(0) : new Thickness(18, 0, 18, 2);
        if (stripped)
        {
            MinSize = System.Numerics.Vector2.Zero;
            SetSize = System.Numerics.Vector2.Zero;
            HorizontalExpand = true;
            VerticalExpand = true;
            OsTitleLabel.Text = "NTOS 1.4™ [REMOTE MATRIX]";
            OsSubtitleLabel.Text = " | Virtual Display Stream";
        }
    }

    public const int DragMarginSize = 7;

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        // Embedded windows (e.g. remote screen inside a terminal) must not be draggable or resizable.
        if (_embedded)
            return DragMode.None;

        var mode = DragMode.Move;

        if (Resizable)
        {
            if (relativeMousePos.Y < DragMarginSize)
            {
                mode = DragMode.Top;
            }
            else if (relativeMousePos.Y > Size.Y - DragMarginSize)
            {
                mode = DragMode.Bottom;
            }

            if (relativeMousePos.X < DragMarginSize)
            {
                mode |= DragMode.Left;
            }
            else if (relativeMousePos.X > Size.X - DragMarginSize)
            {
                mode |= DragMode.Right;
            }
        }

        return mode;
    }
}
