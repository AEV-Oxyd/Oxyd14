using System.Numerics;
using Content.Client.Materials;
using Content.Shared.Lathe;
using Content.Shared.Materials;
using Content.Shared.Research.Prototypes;
using Content.Shared.Stacks;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.Lathe.UI;

[GenerateTypedNameReferences]
public sealed partial class RecipeControl : Control
{
    public Action<string>? OnButtonPressed;
    public Func<string> TooltipTextSupplier;

    public ProtoId<LatheRecipePrototype> RecipeId { get; private set; }
    private LatheSystem _latheSystem;

    public RecipeControl(LatheSystem latheSystem, LatheRecipePrototype recipe, Func<string> tooltipTextSupplier, bool canProduce, Control displayControl, string? recipeName = null)
    {
        RobustXamlLoader.Load(this);

        _latheSystem = latheSystem;
        RecipeId = recipe.ID;
        TooltipTextSupplier = tooltipTextSupplier;
        SetRecipe(recipe, recipeName);
        SetCanProduce(canProduce);
        SetDisplayControl(displayControl);

        Button.OnPressed += (_) =>
        {
            OnButtonPressed?.Invoke(RecipeId);
        };
        Button.TooltipSupplier = SupplyTooltip;
    }

    public void SetRecipe(LatheRecipePrototype recipe, string? recipeName = null)
    {
        RecipeName.Text = recipeName ?? _latheSystem.GetRecipeName(recipe);
        if (recipe.pointUsage != 0)
        {
            DRMCost.Text = $"L-COST:{recipe.pointUsage.ToString()}";
            DRMCost.Visible = true;
        }
        else
        {
            DRMCost.Visible = false;
        }

        RecipeId = recipe.ID;
    }

    public void PopulateMaterials(
        LatheRecipePrototype recipe,
        float multiplier,
        Dictionary<ProtoId<MaterialPrototype>, int>? storedMaterials,
        int requestedQuantity,
        IPrototypeManager protoManager,
        SpriteSystem spriteSystem,
        MaterialStorageSystem materialStorage)
    {
        MaterialsContainer.Children.Clear();

        if (recipe.Materials.Count == 0)
            return;

        foreach (var (matId, baseAmount) in recipe.Materials)
        {
            if (!protoManager.Resolve(matId, out var matProto))
                continue;

            var sheetVolume = materialStorage.GetSheetVolume(matProto);
            var adjustedAmount = SharedLatheSystem.AdjustMaterial(baseAmount, recipe.ApplyMaterialDiscount, multiplier) * requestedQuantity;
            var sheets = adjustedAmount / (float) sheetVolume;

            var storedVolume = 0;
            if (storedMaterials != null && storedMaterials.TryGetValue(matId, out var v))
                storedVolume = v;

            var hasEnough = storedVolume >= adjustedAmount;
            var storedSheets = storedVolume / (float) sheetVolume;

            Texture? iconTex = null;
            // Get stack prototype icon for lowest count (single sheet)
            if (protoManager.TryIndex<StackPrototype>(matId.Id, out var stackProto) && stackProto.Icon != null)
            {
                iconTex = spriteSystem.Frame0(stackProto.Icon);
            }
            else if (matProto.StackEntity != null &&
                     protoManager.TryIndex<EntityPrototype>(matProto.StackEntity.Value, out var entProto) &&
                     entProto.Components.TryGetValue("Stack", out var stackCompReg) &&
                     stackCompReg.Component is StackComponent stackComp &&
                     protoManager.TryIndex<StackPrototype>(stackComp.StackTypeId, out var sProto2) &&
                     sProto2.Icon != null)
            {
                iconTex = spriteSystem.Frame0(sProto2.Icon);
            }
            else if (matProto.Icon != SpriteSpecifier.Invalid)
            {
                iconTex = spriteSystem.Frame0(matProto.Icon);
            }

            var badge = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                VerticalAlignment = VAlignment.Center,
                SeparationOverride = 2,
                ToolTip = $"{Loc.GetString(matProto.Name)}: {(sheets % 1 == 0 ? sheets.ToString("0") : sheets.ToString("0.#"))} (Stored: {(storedSheets % 1 == 0 ? storedSheets.ToString("0") : storedSheets.ToString("0.#"))})"
            };

            if (iconTex != null)
            {
                badge.AddChild(new TextureRect
                {
                    Texture = iconTex,
                    SetSize = new Vector2(18, 18),
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                    VerticalAlignment = VAlignment.Center
                });
            }

            var countLabel = new Label
            {
                Text = sheets % 1 == 0 ? sheets.ToString("0") : sheets.ToString("0.#"),
                FontColorOverride = hasEnough ? Color.FromHex("#C0E0C0") : Color.FromHex("#FF6666"),
                VerticalAlignment = VAlignment.Center
            };
            badge.AddChild(countLabel);

            MaterialsContainer.AddChild(badge);
        }
    }

    public void SetTooltipSupplier(Func<string> tooltipTextSupplier)
    {
        TooltipTextSupplier = tooltipTextSupplier;
    }

    public void SetCanProduce(bool canProduce)
    {
        Button.Disabled = !canProduce;
    }

    public void SetDisplayControl(Control displayControl)
    {
        RecipeDisplayContainer.Children.Clear();
        RecipeDisplayContainer.AddChild(displayControl);
    }

    private Control? SupplyTooltip(Control sender)
    {
        return new RecipeTooltip(TooltipTextSupplier());
    }
}
