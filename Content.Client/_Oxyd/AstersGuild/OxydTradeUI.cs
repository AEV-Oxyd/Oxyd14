/// <summary>Eris trade console BUI (nano/templates/trade.tmpl).</summary>
public sealed class OxydTradeBoundUserInterface : BoundUserInterface
{
    private OxydTradeWindow? _window;

    public OxydTradeBoundUserInterface(EntityUid owner, Enum uiKey) : base(owner, uiKey) { }

    protected override void Open()
    {
        base.Open();
        if (_window != null) return;
        _window = this.CreateWindow<OxydTradeWindow>();
        _window.StationSelected += i => SendMessage(new OxydTradeSelectStationMessage { Index = i });
        _window.CategorySelected += c => SendMessage(new OxydTradeSelectCategoryMessage { Category = c });
        _window.CartAdjust += (id, d) => SendMessage(new OxydTradeCartAdjustMessage { GoodId = id, Delta = d });
        _window.CreateOrder += () => SendMessage(new OxydTradeCreateOrderMessage());
        _window.ResetCart += () => SendMessage(new OxydTradeResetCartMessage());
        _window.SendOffer += id => SendMessage(new OxydTradeSendOfferMessage { OfferId = id });
        _window.OnClose += Close;
    }

    protected override void UpdateState(BoundUserInterfaceState state)
    {
        base.UpdateState(state);
        if (state is OxydTradeState s)
            _window?.UpdateState(s);
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            _window?.Dispose();
            _window = null;
        }
        base.Dispose(disposing);
    }
}

/// <summary>
/// Recreates trade.tmpl: header links (To Trade Screen / Account / Receiving Beacon /
/// Sending Beacon), the station tree (green known rows vs red "???"), the station info
/// panel (name/desc/favor/offer time), tab row Goods|Offers|Cart|Orders|Logs, goods table
/// Name|Price|Available|Cart±, cart lines + Create Order/Save/Load/Reset, offers table with
/// Send checkboxes, and the log list.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class OxydTradeWindow : FancyWindow
{
    public event Action<int>? StationSelected;
    public event Action<string?>? CategorySelected;
    public event Action<int, int>? CartAdjust;
    public event Action? CreateOrder;
    public event Action? ResetCart;
    public event Action<int>? SendOffer;

    private OxydTradeState? _state;
    private string _tab = "Goods";

    public OxydTradeWindow()
    {
        RobustXamlLoader.Load(this);
        Body.PanelOverride = new StyleBoxFlat(ErisNanoColors.BodyBg);
    }

    public void UpdateState(OxydTradeState s)
    {
        _state = s;
        Rebuild();
    }

    private void Rebuild()
    {
        Content.RemoveAllChildren();
        var s = _state!;

        // ---- Header (Eris: account / beacons / balance strip) ----
        var header = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 6 };
        header.AddChild(new ErisLink(s.HasAccount ? "✓Account" : "Account"));
        header.AddChild(new Label { Text = s.ReceivingBeacon, FontColorOverride = ErisNanoColors.LabelText });
        header.AddChild(new Label { Text = s.SendingBeacon, FontColorOverride = ErisNanoColors.LabelText });
        var bal = new ErisItemLabel($"Account Balance: {s.Balance} credits");
        bal.HorizontalAlignment = HAlignment.Right;
        header.AddChild(bal);
        Content.AddChild(ErisCandystripe.Wrap(header, 0));

        // ---- Main split: station tree (left) | content (right) ----
        var split = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8 };

        var treePanel = new ErisPanel();
        var treeCol = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 2 };
        treeCol.AddChild(new ErisItemLabel("Trade stations"));
        for (var i = 0; i < s.Stations.Count; i++)
        {
            var st = s.Stations[i];
            var idx = i;
            var row = new ErisRowButton
            {
                Text = st.Discovered ? st.Name : "???",
                Available = st.Discovered,
                Pressed = i == s.SelectedStation,
            };
            row.RefreshLook();
            row.OnPressed += _ => StationSelected?.Invoke(idx);
            treeCol.AddChild(row);
        }
        treePanel.AddChild(treeCol);
        split.AddChild(treePanel);

        var right = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            SeparationOverride = 4,
            HorizontalExpand = true,
        };

        // Station info panel (Eris right-side spec block).
        var info = new ErisStatusBox();
        var infoCol = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 2 };
        if (s.SelectedStation < 0)
        {
            infoCol.AddChild(new ErisItemLabel("Select a trade station."));
        }
        else
        {
            infoCol.AddChild(new ErisItemLabel($"Name: {s.SelectedName}"));
            infoCol.AddChild(new ErisSubLabel($"Description: {s.SelectedDesc}"));
            var st = s.Stations[s.SelectedStation];
            infoCol.AddChild(new ErisSubLabel($"Favor: {st.Favor}/{st.FavorMax}"));
            var t = st.OfferSecondsLeft;
            infoCol.AddChild(new ErisSubLabel($"Offer Time Remaining: {t / 60:D2}:{t % 60:D2}"));
        }
        info.AddChild(infoCol);
        right.AddChild(info);

        // ---- Tab row (Eris goods|offers|view cart|saved carts|order requests|logs) ----
        var tabs = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 4 };
        foreach (var name in new[] { "Goods", "Offers", "View Cart", "Saved Carts", "Order Requests", "Logs" })
        {
            var n = name;
            var b = new ErisLink(n);
            if (n == _tab) b.SetSelectedLook(); else b.SetUnselectedLook();
            b.OnPressed += _ => { _tab = n; Rebuild(); };
            tabs.AddChild(b);
        }
        right.AddChild(tabs);

        var body = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 2 };
        switch (_tab)
        {
            case "Goods": BuildGoods(body, s); break;
            case "Offers": BuildOffers(body, s); break;
            case "View Cart": BuildCart(body, s); break;
            case "Logs": BuildLogs(body, s); break;
            default: body.AddChild(new ErisSubLabel("Nothing here yet.")); break;
        }
        right.AddChild(body);
        split.AddChild(right);
        Content.AddChild(split);
    }

    private void BuildGoods(BoxContainer body, OxydTradeState s)
    {
        // Category pills.
        var cats = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 4 };
        foreach (var c in s.Categories)
        {
            var cat = c;
            var b = new ErisLink(cat);
            if (cat == s.Category) b.SetSelectedLook(); else b.SetUnselectedLook();
            b.OnPressed += _ => CategorySelected?.Invoke(cat);
            cats.AddChild(b);
        }
        body.AddChild(cats);

        // Table header.
        var head = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8 };
        head.AddChild(new ErisItemLabel("Name"));
        head.AddChild(new ErisItemLabel("Price"));
        head.AddChild(new ErisItemLabel("Available"));
        var cartLbl = new ErisItemLabel("Cart");
        cartLbl.HorizontalAlignment = HAlignment.Right;
        head.AddChild(cartLbl);
        body.AddChild(head);

        if (s.SelectedStation < 0)
            body.AddChild(new ErisSubLabel("Select a trade station."));
        else if (s.Goods.Count == 0)
            body.AddChild(new ErisSubLabel("Nothing to buy here."));

        var i = 0;
        foreach (var g in s.Goods)
        {
            var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8 };
            var name = new Label { Text = g.Name, FontColorOverride = Color.White, MinWidth = 180 };
            name.ClipText = true;
            row.AddChild(name);
            row.AddChild(new Label { Text = $"{g.Price}", FontColorOverride = ErisNanoColors.ItemLabelText, MinWidth = 50 });
            row.AddChild(new Label { Text = $"{g.Available}", FontColorOverride = ErisNanoColors.LabelText, MinWidth = 60 });
            var minus = new ErisLink("-");
            minus.OnPressed += _ => CartAdjust?.Invoke(g.Id, -1);
            var qty = new Label { Text = $" {g.InCart} ", FontColorOverride = Color.White };
            var plus = new ErisLink("+");
            plus.OnPressed += _ => CartAdjust?.Invoke(g.Id, +1);
            row.AddChild(minus); row.AddChild(qty); row.AddChild(plus);
            body.AddChild(ErisCandystripe.Wrap(row, i++));
        }
    }

    private void BuildOffers(BoxContainer body, OxydTradeState s)
    {
        var maxSec = 0;
        foreach (var o in s.Offers) maxSec = Math.Max(maxSec, o.SecondsLeft);
        body.AddChild(new ErisItemLabel($"Special Offers (time left: {maxSec / 60:D2}:{maxSec % 60:D2})"));
        var head = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8 };
        head.AddChild(new ErisItemLabel("Station"));
        head.AddChild(new ErisItemLabel("Name"));
        head.AddChild(new ErisItemLabel("Price"));
        head.AddChild(new ErisItemLabel("Amount"));
        head.AddChild(new ErisItemLabel("Send"));
        body.AddChild(head);
        var i = 0;
        foreach (var o in s.Offers)
        {
            var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8 };
            row.AddChild(new Label { Text = o.Station, FontColorOverride = ErisNanoColors.LabelText, MinWidth = 70 });
            row.AddChild(new Label { Text = o.Name, FontColorOverride = Color.White, MinWidth = 150 });
            row.AddChild(new Label { Text = $"{o.Price}", FontColorOverride = ErisNanoColors.ItemLabelText, MinWidth = 60 });
            row.AddChild(new Label { Text = $"{o.Amount}", FontColorOverride = ErisNanoColors.LabelText, MinWidth = 50 });
            var send = new ErisLink("Send");
            send.OnPressed += _ => SendOffer?.Invoke(o.Id);
            row.AddChild(send);
            body.AddChild(ErisCandystripe.Wrap(row, i++));
        }
        if (s.Offers.Count == 0)
            body.AddChild(new ErisSubLabel("No active offers."));
    }

    private void BuildCart(BoxContainer body, OxydTradeState s)
    {
        body.AddChild(new ErisItemLabel($"Cart ({s.CartCount}) — total {s.CartTotal} credits"));
        var i = 0;
        foreach (var line in s.CartLines)
        {
            body.AddChild(ErisCandystripe.Wrap(
                new Label { Text = line, FontColorOverride = Color.White }, i++));
        }
        if (s.CartLines.Count == 0)
            body.AddChild(new ErisSubLabel("There are no goods in the cart."));
        var btns = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 4 };
        var create = new ErisLink("Create Order");
        create.OnPressed += _ => CreateOrder?.Invoke();
        var save = new ErisLink("Save");
        var load = new ErisLink("Load");
        var reset = new ErisLink("Reset");
        reset.OnPressed += _ => ResetCart?.Invoke();
        btns.AddChild(create); btns.AddChild(save); btns.AddChild(load); btns.AddChild(reset);
        body.AddChild(btns);
    }

    private void BuildLogs(BoxContainer body, OxydTradeState s)
    {
        body.AddChild(new ErisItemLabel("Transaction log"));
        if (s.Log.Count == 0)
            body.AddChild(new ErisSubLabel("Please select a log."));
        var i = 0;
        foreach (var line in s.Log)
            body.AddChild(ErisCandystripe.Wrap(
                new Label { Text = line, FontColorOverride = ErisNanoColors.LabelText }, i++));
    }
}
