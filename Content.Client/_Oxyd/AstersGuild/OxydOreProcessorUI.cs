namespace Content.Client._Oxyd.AstersGuild;

/// <summary>Eris production machine console BUI (TGUI "Processor").</summary>
public sealed class OxydOreProcessorBoundUserInterface : BoundUserInterface
{
    private OxydOreProcessorWindow? _window;

    public OxydOreProcessorBoundUserInterface(EntityUid owner, Enum uiKey) : base(owner, uiKey) { }

    protected override void Open()
    {
        base.Open();
        if (_window != null) return;
        _window = this.CreateWindow<OxydOreProcessorWindow>();
        _window.Toggle += () => SendMessage(new OxydOreProcessorToggleMessage());
        _window.Store += m => SendMessage(new OxydOreProcessorStoreMessage { Material = m });
        _window.Alloy += a => SendMessage(new OxydOreProcessorAlloyMessage { Alloy = a });
        _window.OnClose += Close;
    }

    protected override void UpdateState(BoundUserInterfaceState state)
    {
        base.UpdateState(state);
        if (state is OxydOreProcessorState s)
            _window?.UpdateState(s);
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            _window?.Dispose();
            _window = null;
        }
        base.Dispose(disposing);
    }
}

/// <summary>
/// Recreates the Eris "Processor" screen: TURN ON pill + Melting Rate, "Loaded Materials"
/// table (name, count, Storing action) and the "Alloy Menu" (Plasteel / Steel /
/// Borosilicate glass buttons).
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class OxydOreProcessorWindow : FancyWindow
{
    public event Action? Toggle;
    public event Action<string>? Store;
    public event Action<string>? Alloy;

    private OxydOreProcessorState? _state;

    public OxydOreProcessorWindow()
    {
        RobustXamlLoader.Load(this);
        Body.PanelOverride = new StyleBoxFlat(ErisNanoColors.BodyBg);
    }

    public void UpdateState(OxydOreProcessorState s)
    {
        _state = s;
        Rebuild();
    }

    private void Rebuild()
    {
        Content.RemoveAllChildren();
        var s = _state!;

        var top = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8 };
        var power = new ErisLink("TURN ON", red: !s.Running);
        if (!s.Running) power.Text = "TURN ON"; else { power.Text = "TURN OFF"; power.SetSelectedLook(); }
        power.OnPressed += _ => Toggle?.Invoke();
        top.AddChild(power);
        top.AddChild(new ErisItemLabel("Melting Rate"));
        var bar = new ErisBar();
        bar.SetValue(s.Running ? 1f : 0f, ErisNanoColors.BarGood, s.Running ? "On" : "Off");
        top.AddChild(bar);
        Content.AddChild(ErisCandystripe.Wrap(top, 0));

        if (!s.HasMachine)
        {
            Content.AddChild(new ErisSubLabel("No processing unit in range."));
            return;
        }

        // Loaded Materials (Eris ore list w/ Storing action).
        var mats = new ErisPanel();
        var col = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 2 };
        col.AddChild(new ErisItemLabel("Loaded Materials"));
        var i = 0;
        foreach (var m in s.Materials)
        {
            var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8 };
            var name = new Label { Text = m.Name, FontColorOverride = Color.White, MinWidth = 140 };
            name.ClipText = true;
            row.AddChild(name);
            row.AddChild(new Label { Text = $"{m.Loaded}", FontColorOverride = ErisNanoColors.LabelText, MinWidth = 40 });
            var store = new ErisLink("Storing");
            if (m.Storing) store.SetSelectedLook(); else store.SetUnselectedLook();
            var mat = m.Name;
            store.OnPressed += _ => Store?.Invoke(mat);
            row.AddChild(store);
            col.AddChild(ErisCandystripe.Wrap(row, i++));
        }
        mats.AddChild(col);
        Content.AddChild(mats);

        // Alloy Menu.
        var alloys = new ErisPanel();
        var acol = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 2 };
        acol.AddChild(new ErisItemLabel("Alloy Menu"));
        foreach (var a in s.Alloys)
        {
            var name = a;
            var b = new ErisLink(a);
            b.OnPressed += _ => Alloy?.Invoke(name);
            var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8 };
            row.AddChild(new Label { Text = $"{a}:", FontColorOverride = ErisNanoColors.LabelText, MinWidth = 140 });
            row.AddChild(b);
            acol.AddChild(row);
        }
        alloys.AddChild(acol);
        Content.AddChild(alloys);
    }
}
