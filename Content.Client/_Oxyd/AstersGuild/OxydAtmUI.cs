/// <summary>Eris ATM BUI (economy/ATM.dm NanoUI, ErisNanoStyle).</summary>
public sealed class OxydAtmBoundUserInterface : BoundUserInterface
{
    private OxydAtmWindow? _window;

    public OxydAtmBoundUserInterface(EntityUid owner, Enum uiKey) : base(owner, uiKey) { }

    protected override void Open()
    {
        base.Open();
        if (_window != null) return;
        _window = this.CreateWindow<OxydAtmWindow>();
        _window.Withdraw += a => SendMessage(new OxydAtmWithdrawMessage { Amount = a });
        _window.OnClose += Close;
    }

    protected override void UpdateState(BoundUserInterfaceState state)
    {
        base.UpdateState(state);
        if (state is OxydAtmState s)
            _window?.UpdateState(s);
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            _window?.Dispose();
            _window = null;
        }
        base.Dispose(disposing);
    }
}

/// <summary>
/// Recreates the Eris ATM window (atm.tmpl): guild account balance, withdraw buttons,
/// deposit hint (insert a credits stack on the machine — Eris cash insert).
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class OxydAtmWindow : FancyWindow
{
    public event Action<int>? Withdraw;

    private OxydAtmState? _state;

    public OxydAtmWindow()
    {
        RobustXamlLoader.Load(this);
        Body.PanelOverride = new StyleBoxFlat(ErisNanoColors.BodyBg);
    }

    public void UpdateState(OxydAtmState s)
    {
        _state = s;
        Rebuild();
    }

    private void Rebuild()
    {
        Content.RemoveAllChildren();
        var s = _state!;

        Content.AddChild(ErisCandystripe.Wrap(new ErisItemLabel($"Guild account: {s.Balance}cr"), 0));
        Content.AddChild(new ErisSubLabel("Insert a credits stack on the machine to deposit."));

        var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 4 };
        var w100 = new ErisLink("Withdraw 100");
        w100.OnPressed += _ => Withdraw?.Invoke(100);
        var w500 = new ErisLink("Withdraw 500");
        w500.OnPressed += _ => Withdraw?.Invoke(500);
        row.AddChild(w100);
        row.AddChild(w500);
        Content.AddChild(row);
    }
}
