using Content.Client._Oxyd.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Oxyd.Technomancer.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Oxyd.Technomancer.UI;

/// Pulsar power bridge window — Eris pulsar_power_bridge.tmpl (POWER OUTPUT,
/// LINK pill, reconnect countdown).
[GenerateTypedNameReferences]
public sealed partial class OxydBridgeWindow : FancyWindow
{
    public event Action? Toggle;
    private readonly Label _output = new();
    private readonly Label _status = new();
    private readonly Label _cooldown = new();
    private readonly ErisLink _link;

    public OxydBridgeWindow()
    {
        RobustXamlLoader.Load(this);
        Body.PanelOverride = new Robust.Client.Graphics.StyleBoxFlat(ErisNanoColors.BodyBg);
        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-bridge-power-output")));
        Content.AddChild(_output);
        _status.FontColorOverride = ErisNanoColors.WarningText;
        Content.AddChild(_status);
        _cooldown.FontColorOverride = ErisNanoColors.AccentText;
        Content.AddChild(_cooldown);
        _link = new ErisLink("");
        _link.OnPressed += _ => Toggle?.Invoke();
        Content.AddChild(_link);
    }

    public void Update(OxydPulsarBridgeState s)
    {
        _output.Text = $"{s.InjectedWatts / 1000000f:0.000} MW";
        _status.Text = s.Connected ? Loc.GetString("oxyd-bridge-linked") : Loc.GetString("oxyd-bridge-unlinked");
        _status.FontColorOverride = s.Connected ? ErisNanoColors.GoodText : ErisNanoColors.BadText;
        _cooldown.Text = s.ReconnectCooldown > 0
            ? Loc.GetString("oxyd-bridge-cooldown", ("s", (int)s.ReconnectCooldown))
            : string.Empty;
        _link.Text = s.Connected ? Loc.GetString("oxyd-bridge-disconnect") : Loc.GetString("oxyd-bridge-reconnect");
        if (!s.Connected && s.ReconnectCooldown > 0) _link.SetDisabledLook(); else _link.SetEnabledLook();
    }
}
