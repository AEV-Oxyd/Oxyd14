using Content.Client._Oxyd.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Oxyd.Technomancer.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Oxyd.Technomancer.UI;

/// Breaker box window — Eris simple circuit breaker UI (ENABLED/DISABLED + load).
[GenerateTypedNameReferences]
public sealed partial class OxydBreakerWindow : FancyWindow
{
    public event Action<bool>? SetEnabled;
    private readonly ErisLink _on;
    private readonly ErisLink _off;
    private readonly Label _load = new();
    private OxydBreakerState? _state;

    public OxydBreakerWindow()
    {
        RobustXamlLoader.Load(this);
        Body.PanelOverride = new Robust.Client.Graphics.StyleBoxFlat(ErisNanoColors.BodyBg);
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        _on = new ErisLink(Loc.GetString("oxyd-breaker-on"));
        _off = new ErisLink(Loc.GetString("oxyd-breaker-off"));
        _on.OnPressed += _ => SetEnabled?.Invoke(true);
        _off.OnPressed += _ => SetEnabled?.Invoke(false);
        row.AddChild(_on); row.AddChild(_off);
        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-breaker-state")));
        Content.AddChild(row);
        Content.AddChild(_load);
    }

    public void Update(OxydBreakerState s)
    {
        _state = s;
        if (s.Enabled) { _on.SetSelectedLook(); _off.SetUnselectedLook(); }
        else { _on.SetUnselectedLook(); _off.SetSelectedLook(); }
        _load.Text = Loc.GetString("oxyd-breaker-load", ("w", $"{s.LoadWatts:0}"));
    }
}
