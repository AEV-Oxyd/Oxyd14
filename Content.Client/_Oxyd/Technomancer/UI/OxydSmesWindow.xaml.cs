using Content.Client._Oxyd.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared.Power;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Maths;

namespace Content.Client._Oxyd.Technomancer.UI;

/// <summary>
/// Oxyd SMES control window — recreation of CEV-Eris nano/templates/smes.tmpl:
/// Stored Capacity bar, Input Management (Auto/Off + charge level), Output
/// Management (Online/Offline + output level), Output Load. Speaks the stock
/// BatteryBoundUserInterface protocol (BatteryBuiState / BatterySet* messages)
/// so the stock BatteryInterfaceSystem needs no changes.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class OxydSmesWindow : FancyWindow
{
    public event Action<bool>? InputToggled;
    public event Action<bool>? OutputToggled;
    public event Action<float>? InputRateSet;
    public event Action<float>? OutputRateSet;

    private readonly ErisBar _capacityBar = new();
    private readonly ErisBar _inputBar = new();
    private readonly ErisBar _outputBar = new();
    private readonly ErisBar _loadBar = new();
    private readonly Label _capacityLabel = new();
    private readonly Label _inputState = new();
    private readonly Label _outputState = new();
    private readonly Label _inputWatts = new();
    private readonly Label _outputWatts = new();
    private readonly Label _loadWatts = new();
    private readonly ErisLink _inputAuto;
    private readonly ErisLink _inputOff;
    private readonly ErisLink _outputOnline;
    private readonly ErisLink _outputOffline;
    private readonly ErisLink _inputMin;
    private readonly ErisLink _inputSet;
    private readonly ErisLink _inputMax;
    private readonly ErisLink _outputMin;
    private readonly ErisLink _outputSet;
    private readonly ErisLink _outputMax;

    private BatteryBuiState? _state;

    public OxydSmesWindow()
    {
        RobustXamlLoader.Load(this);
        Body.PanelOverride = new Robust.Client.Graphics.StyleBoxFlat(ErisNanoColors.BodyBg);

        _inputAuto = new ErisLink(Loc.GetString("oxyd-smes-auto"));
        _inputOff = new ErisLink(Loc.GetString("oxyd-smes-off"));
        _outputOnline = new ErisLink(Loc.GetString("oxyd-smes-online"));
        _outputOffline = new ErisLink(Loc.GetString("oxyd-smes-offline"));
        _inputMin = new ErisLink(Loc.GetString("oxyd-smes-min"));
        _inputSet = new ErisLink(Loc.GetString("oxyd-smes-set"));
        _inputMax = new ErisLink(Loc.GetString("oxyd-smes-max"));
        _outputMin = new ErisLink(Loc.GetString("oxyd-smes-min"));
        _outputSet = new ErisLink(Loc.GetString("oxyd-smes-set"));
        _outputMax = new ErisLink(Loc.GetString("oxyd-smes-max"));

        _inputAuto.OnPressed += _ => InputToggled?.Invoke(true);
        _inputOff.OnPressed += _ => InputToggled?.Invoke(false);
        _outputOnline.OnPressed += _ => OutputToggled?.Invoke(true);
        _outputOffline.OnPressed += _ => OutputToggled?.Invoke(false);
        _inputMin.OnPressed += _ => { if (_state != null) InputRateSet?.Invoke(_state.MinMaxChargeRate); };
        _inputMax.OnPressed += _ => { if (_state != null) InputRateSet?.Invoke(_state.MaxMaxChargeRate); };
        _inputSet.OnPressed += _ => AskRate(true);
        _outputMin.OnPressed += _ => { if (_state != null) OutputRateSet?.Invoke(_state.MinMaxSupply); };
        _outputMax.OnPressed += _ => { if (_state != null) OutputRateSet?.Invoke(_state.MaxMaxSupply); };
        _outputSet.OnPressed += _ => AskRate(false);

        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-smes-capacity")));
        Content.AddChild(_capacityBar);
        Content.AddChild(_capacityLabel);

        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-smes-input-mgmt")));
        var inRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        inRow.AddChild(_inputAuto);
        inRow.AddChild(_inputOff);
        inRow.AddChild(_inputState);
        Content.AddChild(inRow);
        Content.AddChild(new ErisSubLabel(Loc.GetString("oxyd-smes-input-level")));
        var inLvl = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        inLvl.AddChild(_inputMin); inLvl.AddChild(_inputSet); inLvl.AddChild(_inputMax); inLvl.AddChild(_inputWatts);
        Content.AddChild(inLvl);
        Content.AddChild(_inputBar);

        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-smes-output-mgmt")));
        var outRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        outRow.AddChild(_outputOnline);
        outRow.AddChild(_outputOffline);
        outRow.AddChild(_outputState);
        Content.AddChild(outRow);
        Content.AddChild(new ErisSubLabel(Loc.GetString("oxyd-smes-output-level")));
        var outLvl = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        outLvl.AddChild(_outputMin); outLvl.AddChild(_outputSet); outLvl.AddChild(_outputMax); outLvl.AddChild(_outputWatts);
        Content.AddChild(outLvl);
        Content.AddChild(_outputBar);

        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-smes-output-load")));
        Content.AddChild(_loadBar);
        Content.AddChild(_loadWatts);
    }

    private void AskRate(bool input)
    {
        if (_state == null)
            return;
        var min = input ? _state.MinMaxChargeRate : _state.MinMaxSupply;
        var max = input ? _state.MaxMaxChargeRate : _state.MaxMaxSupply;
        var cur = input ? _state.MaxChargeRate : _state.MaxSupply;
        var prompt = new OxydRatePrompt(min, max, cur);
        prompt.RateChosen += rate =>
        {
            if (input) InputRateSet?.Invoke(rate);
            else OutputRateSet?.Invoke(rate);
        };
        prompt.OpenCentered();
    }

    public void Update(BatteryBuiState s)
    {
        _state = s;
        var capFrac = s.Capacity > 0 ? s.Charge / s.Capacity : 0f;
        _capacityBar.SetValue(capFrac, ErisNanoColors.BarAverage, "");
        _capacityLabel.Text = Loc.GetString("oxyd-smes-pct", ("pct", (int)(capFrac * 100)));

        _inputAuto.SetSelectedLook(); _inputOff.SetUnselectedLook();
        if (!s.CanCharge) { _inputAuto.SetUnselectedLook(); _inputOff.SetSelectedLook(); }
        _inputState.Text = s.SupplyingNetworkHasPower
            ? Loc.GetString("oxyd-smes-charging")
            : Loc.GetString("oxyd-smes-not-charging");
        _inputState.FontColorOverride = s.SupplyingNetworkHasPower ? ErisNanoColors.GoodText : ErisNanoColors.BadText;

        _outputOnline.SetSelectedLook(); _outputOffline.SetUnselectedLook();
        if (!s.CanDischarge) { _outputOnline.SetUnselectedLook(); _outputOffline.SetSelectedLook(); }
        _outputState.Text = s.LoadingNetworkHasPower
            ? Loc.GetString("oxyd-smes-outputting")
            : Loc.GetString("oxyd-smes-not-outputting");
        _outputState.FontColorOverride = s.LoadingNetworkHasPower ? ErisNanoColors.GoodText : ErisNanoColors.WarningText;

        _inputWatts.Text = $"{s.MaxChargeRate:0} W";
        _outputWatts.Text = $"{s.MaxSupply:0} W";
        _inputBar.SetValue(s.MaxMaxChargeRate > 0 ? (s.MaxChargeRate - s.MinMaxChargeRate) / (s.MaxMaxChargeRate - s.MinMaxChargeRate) : 0f, ErisNanoColors.BarDefault, "");
        _outputBar.SetValue(s.MaxMaxSupply > 0 ? (s.MaxSupply - s.MinMaxSupply) / (s.MaxMaxSupply - s.MinMaxSupply) : 0f, ErisNanoColors.BarDefault, "");
        _loadBar.SetValue(s.MaxMaxSupply > 0 ? Math.Clamp(s.CurrentSupply / s.MaxMaxSupply, 0f, 1f) : 0f, ErisNanoColors.BarAverage, "");
        _loadWatts.Text = $"{s.CurrentSupply:0} W";
    }
}

/// <summary>Tiny numeric prompt for MIN/SET/MAX level entry.</summary>
internal sealed class OxydRatePrompt : FancyWindow
{
    public event Action<float>? RateChosen;

    public OxydRatePrompt(float min, float max, float current)
    {
        Title = Loc.GetString("oxyd-smes-set-title");
        MinSize = new System.Numerics.Vector2(260, 90);
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(8), SeparationOverride = 6, VerticalExpand = true };
        var slider = new Slider { MinValue = min, MaxValue = max, Value = current, HorizontalExpand = true };
        var ok = new ErisLink(Loc.GetString("oxyd-smes-apply"));
        ok.OnPressed += _ => { RateChosen?.Invoke(slider.Value); Close(); };
        box.AddChild(slider);
        box.AddChild(ok);
        AddChild(box);
    }
}
