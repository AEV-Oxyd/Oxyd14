using Content.Client._Oxyd.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Oxyd.Technomancer.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using System.Numerics;
using Robust.Client.UserInterface;
using Robust.Shared.Maths;

namespace Content.Client._Oxyd.Technomancer.UI;

/// Ship shield generator window — Eris shieldgen.tmpl: status, mitigation rows,
/// field size/input cap controls, mode checklist, event log.
[GenerateTypedNameReferences]
public sealed partial class OxydShieldWindow : FancyWindow
{
    public event Action? Toggle;
    public event Action<string, bool>? ModeSet;
    public event Action<int>? FieldSizeSet;
    public event Action<float>? InputCapSet;

    private readonly Label _status = new();
    private readonly ErisBar _integrityBar = new();
    private readonly Label _integrityLabel = new();
    private readonly Label _mitigation = new();
    private readonly Label _upkeep = new();
    private readonly Label _fieldSizeLabel = new();
    private readonly ErisLink _run;
    private readonly ErisLink _fieldDec;
    private readonly ErisLink _fieldInc;
    private readonly ErisLink _capDec;
    private readonly ErisLink _capInc;
    private readonly Label _capLabel = new();
    private readonly BoxContainer _modeList = new() { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 2 };
    private readonly Label _log = new();

    public int CurrentFieldSize;
    public float CurrentInputCap;

    public OxydShieldWindow()
    {
        RobustXamlLoader.Load(this);
        Body.PanelOverride = new Robust.Client.Graphics.StyleBoxFlat(ErisNanoColors.BodyBg);

        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-shield-status")));
        var runRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        _run = new ErisLink("");
        _run.OnPressed += _ => Toggle?.Invoke();
        runRow.AddChild(_run);
        runRow.AddChild(_status);
        Content.AddChild(runRow);
        Content.AddChild(_integrityBar);
        Content.AddChild(_integrityLabel);
        Content.AddChild(_mitigation);
        Content.AddChild(_upkeep);

        var fsRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        fsRow.AddChild(new ErisItemLabel(Loc.GetString("oxyd-shield-field-size")));
        _fieldDec = new ErisLink("-");
        _fieldInc = new ErisLink("+");
        _fieldDec.OnPressed += _ => FieldSizeSet?.Invoke(-10);
        _fieldInc.OnPressed += _ => FieldSizeSet?.Invoke(+10);
        fsRow.AddChild(_fieldDec); fsRow.AddChild(_fieldSizeLabel); fsRow.AddChild(_fieldInc);
        Content.AddChild(fsRow);

        var capRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        capRow.AddChild(new ErisItemLabel(Loc.GetString("oxyd-shield-input-cap")));
        _capDec = new ErisLink("-");
        _capInc = new ErisLink("+");
        _capDec.OnPressed += _ => InputCapSet?.Invoke(-100f);
        _capInc.OnPressed += _ => InputCapSet?.Invoke(+100f);
        capRow.AddChild(_capDec); capRow.AddChild(_capLabel); capRow.AddChild(_capInc);
        Content.AddChild(capRow);

        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-shield-modes")));
        var scroll = new ScrollContainer { VerticalExpand = false, MinSize = new Vector2(0, 150) };
        scroll.AddChild(_modeList);
        Content.AddChild(scroll);

        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-shield-log")));
        _log.StyleClasses.Add("LabelSubText");
        Content.AddChild(_log);
    }

    public void Update(OxydShieldState s)
    {
        _status.Text = s.Running ? Loc.GetString("oxyd-shield-online") : Loc.GetString("oxyd-shield-offline");
        _status.FontColorOverride = s.Running ? ErisNanoColors.GoodText : ErisNanoColors.BadText;
        _run.Text = s.Running ? Loc.GetString("oxyd-shield-power-off") : Loc.GetString("oxyd-shield-power-on");
        var frac = s.Capacity > 0 ? s.Integrity / s.Capacity : 0f;
        _integrityBar.SetValue(frac, frac > 0.6f ? ErisNanoColors.BarGood : ErisNanoColors.BarAverage, "");
        _integrityLabel.Text = $"{s.Integrity:0}/{s.Capacity:0} (cap)";
        _mitigation.Text = $"EM {s.MitigationEm:0}% / PH {s.MitigationPh:0}% / HE {s.MitigationHe:0}% / MAX {s.MitigationMax:0}%";
        _upkeep.Text = $"{s.UpkeepKw:0.0} kW upkeep / {s.TotalUseKw:0.0} kW total";
        _fieldSizeLabel.Text = $"{s.FieldSize}";
        _capLabel.Text = s.InputCap <= 0 ? "MAX" : $"{s.InputCap:0} kW";
        _modeList.DisposeAllChildren();
        foreach (var m in OxydShieldModes.All)
        {
            if (m.HackedOnly && !s.Hacked)
                continue;
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            var btn = new ErisLink(m.Name);
            var on = s.EnabledModes.Contains(m.Id);
            if (on) btn.SetSelectedLook(); else btn.SetUnselectedLook();
            var id = m.Id; var cur = on;
            btn.OnPressed += _ => ModeSet?.Invoke(id, !cur);
            row.AddChild(btn);
            var desc = new Label { Text = m.Desc, FontColorOverride = ErisNanoColors.LabelText, ClipText = true, HorizontalExpand = true };
            row.AddChild(desc);
            _modeList.AddChild(row);
        }
        _log.Text = s.EventLog.Count == 0 ? Loc.GetString("oxyd-shield-no-log") : string.Join("\n", s.EventLog);
    }
}
