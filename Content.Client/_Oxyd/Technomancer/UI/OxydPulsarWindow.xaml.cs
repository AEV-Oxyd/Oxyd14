using Content.Client._Oxyd.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Oxyd.Technomancer.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using System.Numerics;
using Robust.Client.UserInterface;
using Robust.Shared.Maths;

namespace Content.Client._Oxyd.Technomancer.UI;

/// <summary>
/// Oxyd pulsar control console — recreation of CEV-Eris nano/templates/pulsar.tmpl:
/// Power Produced bar, Fuel bar, Shield pill values + bar, effective power,
/// countdown, then the PULSAR map area — emulated as a clickable grid of
/// cell buttons (dark #40628a ship cells, #82C2D8 beams, gold satellite) plus a
/// directional pad, since Oxyd has no BYOND overmap to scroll.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class OxydPulsarWindow : FancyWindow
{
    public event Action<Vector2i>? Move;
    public event Action<int>? ShieldSet;

    private readonly ErisBar _producedBar = new();
    private readonly ErisBar _fuelBar = new();
    private readonly ErisBar _shieldBar = new();
    private readonly Label _producedLabel = new();
    private readonly Label _fuelLabel = new();
    private readonly Label _effectiveLabel = new();
    private readonly Label _countdown = new();
    private readonly GridContainer _grid = new();
    private readonly Dictionary<int, ErisLink> _shieldPills = new();
    private OxydPulsarState? _state;

    public OxydPulsarWindow()
    {
        RobustXamlLoader.Load(this);
        Body.PanelOverride = new Robust.Client.Graphics.StyleBoxFlat(ErisNanoColors.BodyBg);

        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-pulsar-power-produced")));
        Content.AddChild(_producedBar);
        Content.AddChild(_producedLabel);
        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-pulsar-fuel")));
        Content.AddChild(_fuelBar);
        Content.AddChild(_fuelLabel);
        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-pulsar-shield")));
        var pillRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
        foreach (var v in new[] { 0, 45, 70, 100 })
        {
            var pill = new ErisLink($"{v}");
            var val = v;
            pill.OnPressed += _ => ShieldSet?.Invoke(val);
            _shieldPills[v] = pill;
            pillRow.AddChild(pill);
        }
        Content.AddChild(pillRow);
        Content.AddChild(_shieldBar);
        var effRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        effRow.AddChild(new ErisItemLabel(Loc.GetString("oxyd-pulsar-effective")));
        effRow.AddChild(_effectiveLabel);
        Content.AddChild(effRow);
        Content.AddChild(_countdown);
        Content.AddChild(new ErisItemLabel(Loc.GetString("oxyd-pulsar-map")));
        _grid.Columns = 15;
        _grid.MaxSize = new Vector2(390, 390);
        Content.AddChild(_grid);
        var pad = new GridContainer { Columns = 3, HorizontalAlignment = HAlignment.Center };
        var dirs = new (string t, Vector2i d)[]
        {
            ("NW", (-1,-1)), ("N",(0,-1)), ("NE",(1,-1)),
            ("W", (-1,0)),                    ("E",(1,0)),
            ("SW",(-1,1)),  ("S",(0,1)),  ("SE",(1,1)),
        };
        for (var i = 0; i < 9; i++)
        {
            if (i == 4) { pad.AddChild(new Control { MinSize = new Vector2(34, 30) }); continue; }
            var (t, d) = dirs[i < 4 ? i : i - 1];
            var b = new ErisLink(t) { MinSize = new Vector2(34, 30) };
            b.OnPressed += _ => Move?.Invoke(d);
            pad.AddChild(b);
        }
        Content.AddChild(pad);
    }

    private static Color FillFor(float f) =>
        f > 0.6f ? ErisNanoColors.BarGood : f > 0.3f ? ErisNanoColors.BarAverage : ErisNanoColors.BarBad;

    public void Update(OxydPulsarState s)
    {
        _state = s;
        _producedBar.SetValue(s.ProducedFraction, FillFor(s.ProducedFraction), "");
        _producedLabel.Text = Loc.GetString("oxyd-pulsar-pct", ("pct", (int)(s.ProducedFraction * 100)));
        var fuelFrac = s.Fuel / 700f;
        _fuelBar.SetValue(fuelFrac, FillFor(fuelFrac), "");
        _fuelLabel.Text = Loc.GetString("oxyd-pulsar-fuel-detail", ("fuel", s.Fuel), ("cap", 700), ("cost", s.FuelPerMove));
        _shieldBar.SetValue(s.ShieldPower / 100f, ErisNanoColors.BarDefault, "");
        foreach (var (v, pill) in _shieldPills)
        {
            if (v == s.ShieldPower) pill.SetSelectedLook(); else pill.SetUnselectedLook();
        }
        _effectiveLabel.Text = Loc.GetString("oxyd-pulsar-pct", ("pct", (int)(s.EffectiveFraction * 100)));
        _effectiveLabel.FontColorOverride = s.ShieldPower * s.ShieldNeededPct / 100f >= s.EffectiveFraction
            ? ErisNanoColors.WarningText : ErisNanoColors.Text;
        var m = (int)(s.OrbitDecaySeconds / 60);
        var sec = (int)(s.OrbitDecaySeconds % 60);
        _countdown.Text = Loc.GetString("oxyd-pulsar-countdown", ("t", $"{m:0}:{sec:00}"));
        _countdown.FontColorOverride = ErisNanoColors.AccentText;
        RebuildGrid(s);
    }

    private void RebuildGrid(OxydPulsarState s)
    {
        _grid.DisposeAllChildren();
        _grid.Columns = s.GridSize;
        var beams = new HashSet<Vector2i>(s.Beams);
        for (var y = 0; y < s.GridSize; y++)
        for (var x = 0; x < s.GridSize; x++)
        {
            var pos = new Vector2i(x, y);
            var cell = new PanelContainer
            {
                MinSize = new Vector2(390f / s.GridSize - 1, 390f / s.GridSize - 1),
            };
            Color bg = Color.FromHex("#00005f"); // Eris empty-ocean tile
            if (beams.Contains(pos)) bg = Color.FromHex("#82C2D8");
            if (pos == s.SatellitePos) bg = Color.FromHex("#e9c183");
            cell.PanelOverride = new Robust.Client.Graphics.StyleBoxFlat(bg);
            _grid.AddChild(cell);
        }
    }
}
