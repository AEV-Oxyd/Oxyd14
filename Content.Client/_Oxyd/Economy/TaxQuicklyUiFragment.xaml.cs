using System.Globalization;
using System.Linq;
using Content.Shared._Oxyd.Economy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Oxyd.Economy;

[GenerateTypedNameReferences]
public sealed partial class TaxQuicklyUiFragment : BoxContainer
{
    public event Action<TaxQuicklyUiAction, int, int, int, int, string?>? OnAction;

    public TaxQuicklyUiFragment()
    {
        RobustXamlLoader.Load(this);
        LoginButton.OnPressed += _ => Emit(TaxQuicklyUiAction.Login);
        LogoutButton.OnPressed += _ => Emit(TaxQuicklyUiAction.Logout);
        TransferButton.OnPressed += _ => Emit(TaxQuicklyUiAction.Transfer);
        ResignButton.OnPressed += _ => Emit(TaxQuicklyUiAction.Resign);
        LinkButton.OnPressed += _ => Emit(TaxQuicklyUiAction.LinkEmployee);
        SetWageButton.OnPressed += _ => Emit(TaxQuicklyUiAction.SetWage);
        DisavowButton.OnPressed += _ => Emit(TaxQuicklyUiAction.DisavowEmployee);
        RegPersonalButton.OnPressed += _ => Emit(TaxQuicklyUiAction.RegisterPersonal);
        RegDeptButton.OnPressed += _ => Emit(TaxQuicklyUiAction.RegisterDepartment);
        RefreshButton.OnPressed += _ => Emit(TaxQuicklyUiAction.Refresh);
    }

    public void UpdateState(TaxQuicklyUiState state)
    {
        ErrorLabel.Visible = state.Error != null;
        ErrorLabel.Text = state.Error ?? string.Empty;

        if (!state.LoggedIn)
        {
            StatusLabel.Text = "Not logged in";
            LogLabel.Text = string.Empty;
            return;
        }

        StatusLabel.Text =
            $"#{state.AccountNumber} {state.OwnerName} | bal {state.Balance} | wage {state.Wage} | debt {state.Debt} | emp {state.Employer}"
            + (state.IsDepartment ? " [DEPT]" : string.Empty)
            + (state.CanMakeAccounts ? " [CAN_MAKE]" : string.Empty);

        LogLabel.Text = string.Join('\n',
            state.Transactions.Select(t => $"{t.Amount:+#;-#;0} {t.Purpose} ({t.SourceTerminal})"));
    }

    private void Emit(TaxQuicklyUiAction action)
    {
        int.TryParse(AccountEdit.Text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var account);
        int.TryParse(PinEdit.Text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var pin);
        int.TryParse(TargetEdit.Text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var target);
        int.TryParse(AmountEdit.Text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var amount);
        OnAction?.Invoke(action, account, pin, target, amount, NameEdit.Text);
    }
}
