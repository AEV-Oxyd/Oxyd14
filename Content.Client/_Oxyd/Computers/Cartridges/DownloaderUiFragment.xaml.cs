using Content.Client.UserInterface.StateRouting;
using Content.Client._Oxyd.UI.Style;
using Content.Shared._Oxyd.Computers.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Oxyd.Computers.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class DownloaderUiFragment : BoxContainer, IBuiStateReceiver
{
    private readonly BuiStateHandlers _handlers = new();
    public BuiStateReceiveResult ReceiveBuiState(BoundUserInterfaceState s) => _handlers.Receive(s);

    public event Action? OnRefresh;
    public event Action<string>? OnSelectCategory;
    public event Action<string>? OnDownloadItem;
    public event Action<string>? OnInstallProgram;

    public DownloaderUiFragment()
    {
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;

        _handlers.On<DownloaderUiState>(UpdateState);

        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();

        CatAllButton.OnPressed += _ => OnSelectCategory?.Invoke("All");
        CatProgramsButton.OnPressed += _ => OnSelectCategory?.Invoke("Programs");
        CatDatabasesButton.OnPressed += _ => OnSelectCategory?.Invoke("Databases");
        CatBlueprintsButton.OnPressed += _ => OnSelectCategory?.Invoke("Blueprints");
        CatDocsButton.OnPressed += _ => OnSelectCategory?.Invoke("Documents");
    }

    public void UpdateState(DownloaderUiState state)
    {
        ServerHeaderLabel.Text = $"SERVER: {state.ServerName} [{state.ServerGuid}]";
        LinkSpeedLabel.Text = $"LINK: {state.BandwidthBps / 1024} KB/s | STATUS: {(state.IsServerOnline ? "ONLINE" : "OFFLINE")}";
        StatusMessageLabel.Text = state.StatusMessage;
        StatusPanel.Visible = !string.IsNullOrWhiteSpace(state.StatusMessage);

        CatalogContainer.RemoveAllChildren();

        if (state.Items.Count == 0)
        {
            var emptyLabel = new Label
            {
                Text = "(No items available in this category)",
                FontColorOverride = Color.Gray,
                Margin = new Thickness(8)
            };
            CatalogContainer.AddChild(emptyLabel);
            return;
        }

        foreach (var item in state.Items)
        {
            var card = new PanelContainer
            {
                StyleClasses = { "ErisStyleDigital" },
                Margin = new Thickness(0, 2),
                HorizontalExpand = true
            };

            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(6, 4)
            };

            var infoBox = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                HorizontalExpand = true
            };

            var titleRow = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal
            };

            var titleLabel = new Label
            {
                Text = item.Name,
                StyleClasses = { "LabelHeading" },
                FontColorOverride = Color.FromHex("#00D4FF")
            };
            titleRow.AddChild(titleLabel);

            var catLabel = new Label
            {
                Text = $" [{item.Category}]",
                StyleClasses = { "LabelSubText" },
                FontColorOverride = Color.FromHex("#FFE066"),
                Margin = new Thickness(6, 0)
            };
            titleRow.AddChild(catLabel);

            var sizeLabel = new Label
            {
                Text = item.Size < 1024 ? $"({item.Size} B)" : $"({item.Size / 1024.0:0.#} KB)",
                StyleClasses = { "LabelSubText" },
                FontColorOverride = Color.FromHex("#88AAAA")
            };
            titleRow.AddChild(sizeLabel);

            infoBox.AddChild(titleRow);

            var descLabel = new Label
            {
                Text = item.Description,
                StyleClasses = { "LabelSubText" },
                FontColorOverride = Color.FromHex("#CCCCCC")
            };
            infoBox.AddChild(descLabel);

            row.AddChild(infoBox);

            // Action button
            if (!string.IsNullOrEmpty(item.PrototypeId))
            {
                if (item.IsInstalled)
                {
                    var installedLabel = new Label
                    {
                        Text = "[Installed]",
                        FontColorOverride = Color.FromHex("#00FF88"),
                        VerticalAlignment = VAlignment.Center,
                        Margin = new Thickness(8, 0)
                    };
                    row.AddChild(installedLabel);
                }
                else
                {
                    var instBtn = new Button
                    {
                        Text = "Install",
                        SetWidth = 85,
                        StyleClasses = { ErisSheetlet.StyleClassErisHoloButton },
                        VerticalAlignment = VAlignment.Center
                    };
                    instBtn.OnPressed += _ => OnInstallProgram?.Invoke(item.Id);
                    row.AddChild(instBtn);
                }
            }
            else
            {
                if (item.IsDownloaded)
                {
                    var storedLabel = new Label
                    {
                        Text = "[Downloaded]",
                        FontColorOverride = Color.FromHex("#00D4FF"),
                        VerticalAlignment = VAlignment.Center,
                        Margin = new Thickness(8, 0)
                    };
                    row.AddChild(storedLabel);
                }
                else
                {
                    var dlBtn = new Button
                    {
                        Text = "Download",
                        SetWidth = 85,
                        StyleClasses = { ErisSheetlet.StyleClassErisHoloButton },
                        VerticalAlignment = VAlignment.Center
                    };
                    dlBtn.OnPressed += _ => OnDownloadItem?.Invoke(item.Id);
                    row.AddChild(dlBtn);
                }
            }

            card.AddChild(row);
            CatalogContainer.AddChild(card);
        }
    }
}
