using Content.Client._Oxyd.Computers.ScreenSharing;
using Content.Client.UserInterface.Fragments;
using Content.Client.UserInterface.StateRouting;
using Content.Shared._Oxyd.Computers.Cartridges;
using Content.Shared._Oxyd.Computers.ScreenSharing;
using Content.Shared.CartridgeLoader;
using Content.Shared.PDA;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Oxyd.Computers.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class TerminalUiFragment : BoxContainer, IBuiStateReceiver
{
    private readonly BuiStateHandlers _handlers = new();
    public BuiStateReceiveResult ReceiveBuiState(BoundUserInterfaceState s) => _handlers.Receive(s);

    public event Action<string>? OnSendCommand;
    public event Action<string?, string?>? OnRemoteAction;
    private bool _isScreenAttached;
    private RemoteScreenView? _remoteScreenView;

    /// <summary>
    /// The bound user interface hosting this terminal (the viewer's PDA). Remote program fragments send their
    /// messages through it; the server-side terminal forwards them to the remote device's active program.
    /// </summary>
    public BoundUserInterface? HostBui;
    public TerminalUiFragment()
    {
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;

        _handlers.On<TerminalUiState>(UpdateState);

        CommandLineInput.OnTextEntered += args => SubmitCommand(args.Text);
        SendButton.OnPressed += _ => SubmitCommand(CommandLineInput.Text);

        ClearButton.OnPressed += _ => OnSendCommand?.Invoke("clear");
        KeygenButton.OnPressed += _ => OnSendCommand?.Invoke("keygen");
        ExitSshButton.OnPressed += _ => OnSendCommand?.Invoke("exit");
        SwitchShellButton.OnPressed += _ => OnSendCommand?.Invoke("switch");
        DetachScreenButton.OnPressed += _ => OnSendCommand?.Invoke("screen close");
        ScreenButton.OnPressed += _ =>
        {
            if (_isScreenAttached)
            {
                OnSendCommand?.Invoke("screen close");
            }
            else
            {
                OnSendCommand?.Invoke("screen open");
            }
        };

        AutoScrollCheckBox.OnToggled += args =>
        {
            TerminalOutput.ScrollFollowing = args.Pressed;
            if (args.Pressed)
                TerminalOutput.ScrollToBottom();
        };
    }

    private void SubmitCommand(string text)
    {
        if (string.IsNullOrWhiteSpace(text))
            return;

        OnSendCommand?.Invoke(text.Trim());
        CommandLineInput.Text = string.Empty;
    }

    public void UpdateState(TerminalUiState state)
    {
        _isScreenAttached = state.IsScreenAttached;
        PromptLabel.Text = state.Prompt;
        PromptLabel.FontColorOverride = state.IsPasswordPrompt ? Color.Yellow : Color.FromHex("#00FF88");

        TerminalOutputContainer.Visible = !state.IsScreenAttached;
        TerminalScreenContainer.Visible = state.IsScreenAttached;

        var remoteScreen = state.RemoteScreen;
        if (remoteScreen == null && state.RemotePdaState != null)
        {
            remoteScreen = new RemoteScreenState(
                NetEntity.Invalid,
                state.SshHost ?? string.Empty,
                state.SshHost ?? "REMOTE",
                pdaState: state.RemotePdaState);
        }

        if (state.IsScreenAttached && remoteScreen != null)
        {
            if (_remoteScreenView == null)
            {
                _remoteScreenView = new RemoteScreenView
                {
                    HostBui = HostBui
                };
                _remoteScreenView.OnRemoteAction += (act, arg) => OnRemoteAction?.Invoke(act, arg);

                TerminalScreenSlot.RemoveAllChildren();
                TerminalScreenSlot.AddChild(_remoteScreenView);
            }
            else
            {
                _remoteScreenView.HostBui = HostBui;
            }

            var devTitle = string.IsNullOrEmpty(remoteScreen.DeviceName)
                ? $"[{state.SshHost ?? remoteScreen.DeviceGuid}]"
                : $"{remoteScreen.DeviceName.ToUpperInvariant()} [{state.SshHost ?? remoteScreen.DeviceGuid}]";
            ScreenStatusLabel.Text = $"REMOTE SCREEN MATRIX: {devTitle} [PIP STREAM]";
            _remoteScreenView.UpdateState(remoteScreen);
        }
        else
        {
            if (_remoteScreenView != null)
            {
                TerminalScreenSlot.RemoveAllChildren();
                _remoteScreenView.Dispose();
                _remoteScreenView = null;
            }
        }

        if (state.IsPasswordPrompt)
        {
            CommandLineInput.PlaceHolder = "Enter SSH password or authentication key...";
            SwitchShellButton.Visible = false;
            ScreenButton.Visible = false;
        }
        else if (!string.IsNullOrEmpty(state.SshHost))
        {
            ExitSshButton.Visible = true;
            SwitchShellButton.Visible = true;
            SwitchShellButton.Text = state.IsSshLocalMode ? "To Remote" : "To Local";
            ScreenButton.Visible = true;
            ScreenButton.Text = state.IsScreenAttached ? "Console" : "Screen";

            if (state.IsSshLocalMode)
            {
                ConnectionStatusLabel.Text = $"MODE: SSH [{state.SshHost}] (LOCAL SHELL ACTIVE)";
                ConnectionStatusLabel.FontColorOverride = Color.FromHex("#FFB800");
                CommandLineInput.PlaceHolder = "Local shell active (run local dirs/commands or 'switch'/'remote')...";
            }
            else
            {
                ConnectionStatusLabel.Text = $"MODE: SSH SESSION -> [{state.SshHost}]";
                ConnectionStatusLabel.FontColorOverride = Color.FromHex("#00FF88");
                CommandLineInput.PlaceHolder = "Remote shell active (type 'help', 'ls', 'screen', 'switch', 'exit')...";
            }
        }
        else
        {
            ConnectionStatusLabel.Text = $"MODE: LOCAL SHELL (ID: [{state.DeviceGuid}])";
            ConnectionStatusLabel.FontColorOverride = Color.FromHex("#00D4FF");
            ExitSshButton.Visible = false;
            SwitchShellButton.Visible = false;
            ScreenButton.Visible = false;
            CommandLineInput.PlaceHolder = "Enter command (e.g. 'help', 'ssh [guid]', 'ls', 'ping [guid]')...";
        }

        TerminalOutput.Clear();
        TerminalOutput.ScrollFollowing = AutoScrollCheckBox.Pressed;

        foreach (var line in state.Lines)
        {
            var msg = new FormattedMessage();
            msg.PushColor(GetColorForLine(line));
            msg.AddText(line);
            msg.Pop();
            TerminalOutput.AddMessage(msg);
        }

        if (AutoScrollCheckBox.Pressed)
        {
            TerminalOutput.ScrollToBottom();
        }
    }

    private Color GetColorForLine(string line)
    {
        if (line.StartsWith("ssh:") || line.StartsWith("ping:") || line.Contains("denied") || line.Contains("error") || line.Contains("failed"))
            return Color.FromHex("#FF5555");
        if (line.StartsWith("PING") || line.StartsWith("Authenticated") || line.Contains("Success") || line.Contains("Transferred"))
            return Color.FromHex("#00FF88");
        if (line.StartsWith("[") || line.Contains("@"))
            return Color.FromHex("#00D4FF");
        if (line.StartsWith("Directory:") || line.StartsWith("Host:") || line.StartsWith("Available"))
            return Color.FromHex("#FFE066");
        return Color.FromHex("#E0F7FA");
    }
}
