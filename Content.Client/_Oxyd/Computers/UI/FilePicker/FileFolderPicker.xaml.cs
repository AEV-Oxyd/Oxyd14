using Content.Shared._Oxyd.Computers.FileSystem;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Content.Client.UserInterface.Controls.FancyTree;

namespace Content.Client._Oxyd.Computers.UI.FilePicker;

[GenerateTypedNameReferences]
public sealed partial class FileFolderPicker : BoxContainer
{
    public event Action<string>? OnFolderSelected;
    public event Action<FileHeader>? OnFileSelected;

    public string CurrentPath { get; private set; } = "/";
    private readonly List<FileHeader> _allFiles = new();
    private readonly List<string> _allDirectories = new();

    public FileFolderPicker()
    {
        RobustXamlLoader.Load(this);

        UpButton.OnPressed += _ => NavigateUp();
        SelectFolderButton.OnPressed += _ =>
        {
            OnFolderSelected?.Invoke(CurrentPath);
        };

        SelectFileButton.OnPressed += _ =>
        {
            if (FileTree.SelectedItem?.Metadata is FileHeader header)
            {
                OnFileSelected?.Invoke(header);
            }
        };

        FileTree.OnSelectedItemChanged += OnTreeSelectionChanged;
    }

    public void Populate(List<FileHeader> files, List<string> directories, string currentPath = "/")
    {
        _allFiles.Clear();
        _allFiles.AddRange(files);
        _allDirectories.Clear();
        _allDirectories.AddRange(directories);

        SetDirectory(currentPath);
    }

    public void SetDirectory(string dir)
    {
        if (!dir.StartsWith('/')) dir = "/" + dir;
        if (!dir.EndsWith('/')) dir += "/";

        CurrentPath = dir;
        CurrentPathLabel.Text = CurrentPath;
        FileTree.Clear();

        // Add subdirectories
        foreach (var d in _allDirectories)
        {
            if (d == CurrentPath || !d.StartsWith(CurrentPath))
                continue;

            var remainder = d.Substring(CurrentPath.Length);
            var parts = remainder.Split('/', StringSplitOptions.RemoveEmptyEntries);
            if (parts.Length == 1)
            {
                var item = FileTree.AddItem();
                item.Label.Text = "📁 " + parts[0];
                item.Metadata = d;
            }
        }

        // Add files in this directory
        foreach (var f in _allFiles)
        {
            var fDir = f.Path.Substring(0, f.Path.LastIndexOf('/') + 1);
            if (fDir == CurrentPath)
            {
                var item = FileTree.AddItem();
                var prefix = f.IsEncrypted ? "🔒 " : "📄 ";
                item.Label.Text = $"{prefix}{f.Name}.{f.Extension} ({f.Size} B)";
                item.Metadata = f;
            }
        }
    }

    private void NavigateUp()
    {
        if (CurrentPath == "/")
            return;

        var trimmed = CurrentPath.TrimEnd('/');
        var lastSlash = trimmed.LastIndexOf('/');
        if (lastSlash >= 0)
        {
            var parent = trimmed.Substring(0, lastSlash + 1);
            SetDirectory(parent);
        }
    }

    private void OnTreeSelectionChanged(TreeItem? item)
    {
        if (item == null)
        {
            SelectedNameLabel.Text = "No selection";
            return;
        }

        if (item.Metadata is string dirPath)
        {
            SelectedNameLabel.Text = "Folder: " + dirPath;
            SetDirectory(dirPath);
        }
        else if (item.Metadata is FileHeader file)
        {
            SelectedNameLabel.Text = $"File: {file.Name}.{file.Extension}";
        }
    }
}
