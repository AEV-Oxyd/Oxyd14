    /// <summary>Eris condition list: (label, fixing step) — matches the server's BuildWounds set.</summary>
    private static List<(string Name, OxydSurgeryStep Fix)> ConditionsFor(OxydSurgeryOrganEntry organ)
    {
        var list = new List<(string, OxydSurgeryStep)>();
        if (organ is { Incision: not OxydIncisionStage.None, Clamped: false })
            list.Add((Loc.GetString("oxyd-surgery-cond-bleeding"), OxydSurgeryStep.FixBleeding));
        if (organ.Fractured)
            list.Add((Loc.GetString("oxyd-surgery-cond-fracture"), OxydSurgeryStep.MendBone));
        if (organ.EmbeddedCount > 0)
            list.Add((Loc.GetString("oxyd-surgery-cond-embedded"), OxydSurgeryStep.RemoveEmbedded));
        if (organ is { OrganDamage: > 0, Robotic: false })
            list.Add((Loc.GetString("oxyd-surgery-cond-damage"), OxydSurgeryStep.FixOrgan));
        if (organ is { OrganDamage: > 0, Robotic: true })
            list.Add((Loc.GetString("oxyd-surgery-cond-robo"), OxydSurgeryStep.RoboFixBrute));
        return list;
    }

    /// <summary>Eris &lt;header&gt;&lt;h3&gt;: white heading over a 2px accent underline.</summary>
    private static Control MakeHeader(string text, Color? underline = null)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 2 };
        box.AddChild(new Label
        {
            Text = text,
            StyleClasses = { StyleClass.LabelSubHeading },
            FontColorOverride = Color.White,
        });
        box.AddChild(new PanelContainer
        {
            MinHeight = 2,
            PanelOverride = new StyleBoxFlat(underline ?? ErisSurgeryColors.CardBorder),
        });
        return box;
    }

    /// <summary>Eris &lt;section&gt;: a .label cell then a .content cell. The label cell is a
    /// fixed-width column (default 130px, fits "Occupied space:" etc.) with ClipText so
    /// overlong labels truncate instead of drawing over the value — ClipText without an
    /// explicit width collapses the label's measure to zero, so the width must stay.
    /// Pass width 0 for a natural-width label in a roomy row (e.g. the Conditions card).</summary>
    private static BoxContainer MakeSectionRow(string label, float width = 130)
    {
        var cell = new Label
        {
            Text = label,
            FontColorOverride = ErisSurgeryColors.LabelText,
            HorizontalExpand = false,
        };
        if (width > 0)
        {
            cell.SetWidth = width;
            cell.ClipText = true;
        }
        var row = new BoxContainer { SeparationOverride = 6 };
        row.AddChild(cell);
        return row;
    }

    /// <summary>Wrapping body text — nanoUI reflows long lines inside the card; a plain
    /// Label just draws past the card bounds. RichTextLabel wraps at its own width.</summary>
    private static RichTextLabel MakeText(string text, Color color)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(text, color);
        return label;
    }

    private static ErisBar MakeBar(float fraction, Color fill, string text)
    {
        var bar = new ErisBar { HorizontalExpand = true };
        bar.SetValue(fraction, fill, text);
        return bar;
    }

    private static string TitleCase(string name) =>
        string.IsNullOrEmpty(name) ? name : string.Concat(name[..1].ToUpperInvariant(), name[1..]);
}
